/**
 * Собирает схему из декларации. Поле — пара [ключ, тип], где тип это
 * 'num' (число), 'str' (строка) или массив допустимых значений (enum).
 *
 * Enum — не украшение: значения из закрытого списка это готовые фасеты
 * фильтра. «Фронтальная», «фронтальный тип загрузки» и «front load» в одном
 * поле дают три разных фильтра вместо одного.
 */
function defineSchema(s) {
  const specKeys    = s.fields.map(([k]) => k);
  const numericKeys = s.fields.filter(([, t]) => t === 'num').map(([k]) => k);
  const enums       = Object.fromEntries(s.fields.filter(([, t]) => Array.isArray(t)).map(([k, t]) => [k, t]));
  const labels      = (s.labelKeys || [])
    .filter(k => { if (LABEL[k]) return true; throw new Error(`нет подписи для ${k}`); })
    .map(k => [k, LABEL[k][0], LABEL[k][1]])
    .concat(s.labels || []);
  return {
    slug: s.slug, id: s.id ?? null, name: s.name, subject: s.subject,
    specKeys, numericKeys, enums, labels,
    attrs:     s.attrs || [],
    ranges:    { ...COMMON_RANGE, ...(s.ranges || {}) },
    tallest:   s.tallest !== false,
    extra:     s.extra || NOOP,
    unitNotes: s.unitNotes || [],
    hints:     s.hints || [],
  };
}


/**
 * Извлекает из текста то, что берётся однозначно. Используется и как проверка
 * ответа модели, и как подсказка модели в промпте, и для добора пустых полей.
 */
export function extractFacts(text, schemaKey) {
  const t = String(text || '');
  if (!t) return {};
  const s = schemaFor(schemaKey);
  if (s.fromDictionary && s.dict) {
    const plain = stripHtml(t);
    const common = commonFacts(plain, s);
    const fromDict = extractFactsFromDictionary(t, s.dict, loadConfigSafe());
    const f = { ...fromDict, ...common };
    // Тройка из текста: оси, которые commonFacts отбросил (лживая подпись),
    // не должны вернуться из справочника.
    if (common.размеры_мм) {
      for (const k of ['высота_мм', 'ширина_мм', 'глубина_мм']) {
        if (common[k] != null) f[k] = common[k];
        else delete f[k];
      }
    }
    for (const key of s.specKeys || []) {
      if (key === 'гарантия_мес') continue; // только extractWarrantyMonths
      if (f[key] != null || !LABEL[key]) continue;
      const [lab, unit] = LABEL[key];
      const h = labeled(plain, lab);
      if (!h || !inRange(key, h.value, s.ranges)) continue;
      if (unit && !unit.test(h.tail) && !unit.test(h.gap) && !unit.test(h.head)) continue;
      f[key] = h.value;
    }
    return f;
  }
  const f = commonFacts(t, s);

  for (const [key, label, unit] of s.labels) {
    if (key === 'гарантия_мес') continue;
    const h = labeled(t, label);
    if (!h || !inRange(key, h.value, s.ranges)) continue;
    if (unit && !unit.test(h.tail) && !unit.test(h.gap) && !unit.test(h.head)) continue;
    f[key] = h.value;
  }

  s.extra(t, f, s.ranges);
  return f;
}

/**
 * Атрибуты товара → { facts, bounds, sources }. Первые два по полям схемы,
 * sources хранит исходную строку атрибута: без неё расхождение показывается
 * числом без объяснения, откуда оно взялось.
 */
export function attrFacts(attributes, schemaKey) {
  const s = schemaFor(schemaKey);
  const facts = {}, bounds = {}, sources = {};
  if (s.fromDictionary && s.dict) {
    const list = Array.isArray(attributes) ? attributes : [];
    const cfg = loadConfigSafe();
    const fuzzyMin = cfg?.fuzzy?.min_score ?? 0.9;
    for (const a of list) {
      const name = String(a?.name ?? '');
      const raw = String(a?.value ?? '').trim();
      if (!name || !raw) continue;
      const matched = matchKey(name, s.dict, { value: raw, fuzzyMin });
      if (!matched.attr || matched.attr.tier === 'X') continue;
      const attr = matched.attr;
      const dest = specDest(attr);
      const key = typeof dest === 'object' ? dest.key : dest;
      const mul = typeof dest === 'object' ? dest.mul : 1;
      const src = `${name}: ${a.value}`;

      if (attr.type === 'number' || attr.type === 'integer') {
        const got = parseRange(raw, mul);
        if (got == null) continue;
        sources[key] = src;
        if (typeof got === 'object') bounds[key] = { ...got, source: src };
        else if (inRange(key, got, s.ranges)) facts[key] = got;
        continue;
      }

      // Несколько вариантов через «/» — фасет фильтра, не характеристика.
      if (attr.type === 'enum' && /\/| или /i.test(raw)) {
        const hits = pickEnum(raw, COOLING_VARIANTS);
        if (attr.code === 'cooling' && hits == null) continue;
        if (attr.code !== 'cooling' && /\/| или /i.test(raw)) continue;
      }

      if (attr.code === 'cooling') {
        const snapped = pickEnum(raw, COOLING_VARIANTS);
        if (snapped == null) continue;
        facts[key] = displayEnum(snapped) || snapped;
        sources[key] = src;
        continue;
      }

      const norm = normalizeValue(attr, raw, { keyText: name });
      if (!norm.ok) continue;
      let val = norm.value;
      if (typeof val === 'number' && mul !== 1) val = Math.round(val * mul * 1000) / 1000;
      if (Array.isArray(val)) val = val[0];
      facts[key] = val;
      sources[key] = src;
    }
    return { facts, bounds, sources };
  }
  for (const a of Array.isArray(attributes) ? attributes : []) {
    const name = String(a?.name ?? '');
    const spec = s.attrs.find(([, re]) => re.test(name));
    if (!spec) continue;
    const [key, , parse] = spec;
    const got = parse(String(a?.value ?? ''));
    if (got == null) continue;
    sources[key] = `${name}: ${a.value}`;
    if (typeof got === 'object') bounds[key] = { ...got, source: sources[key] };
    else if (typeof got === 'string' || inRange(key, got, s.ranges)) facts[key] = got;
  }
  return { facts, bounds, sources };
}

/**
 * Факты товара из обоих источников сразу. Расходятся — не утверждаем ничего:
 * тот же принцип, что и с «No Frost» рядом с «капельной» внутри одного текста.
 * Спор магазина с самим собой не разрешается догадкой в нашу пользу.
 *
 * Annotation с HTML (<li>) даёт границы пар надёжнее, чем stripHtml(sourceText):
 * иначе synonym «Программы» проглатывает соседние строки и крадёт «24 ч» отсрочки.
 */
export function productFacts(product, schemaKey) {
  const plain = sourceText(product);
  const fromPlain = extractFacts(plain, schemaKey);
  // Сырой annotation/description — пока HTML жив; поверх plain.
  const fromAnn = product?.annotation ? extractFacts(String(product.annotation), schemaKey) : {};
  const fromDesc = product?.description ? extractFacts(String(product.description), schemaKey) : {};
  const facts = { ...fromPlain, ...fromDesc, ...fromAnn };
  const { facts: attr, bounds, sources } = attrFacts(product?.attributes, schemaKey);
  // Спор не проглатывается молча: это ошибка в самом каталоге, и её владелец —
  // магазин, а не модель. Собираем отдельно от warnings, которые про модель.
  const conflicts = [];
  const drop = (field, text) => {
    conflicts.push({ field, text, attr: sources[field] });
    delete facts[field];
    delete bounds[field];
  };

  for (const [k, v] of Object.entries(attr)) {
    if (!(k in facts)) { facts[k] = v; continue; }
    if (!sameFact(k, facts[k], v)) drop(k, facts[k]);
  }
  // Число из текста вне интервала атрибута — тот же спор источников.
  for (const [k, b] of Object.entries(bounds)) {
    if (facts[k] == null) continue;
    if (withinBound(k, Number(facts[k]), b)) delete bounds[k];  // интервал уже подтверждён точным числом
    else drop(k, facts[k]);
  }
  return { facts, bounds, conflicts };
}

/** Boolean и алиасы → «да»/«нет», чтобы false из атрибута совпадал с «нет» модели. */
function canonBoolish(v) {
  if (typeof v === 'boolean') return v ? 'да' : 'нет';
  if (v == null) return null;
  const low = String(v).trim().toLowerCase();
  if (!low) return null;
  if (['да', 'true', 'yes', 'есть', 'имеется', 'присутствует', '+', 'on'].includes(low)) return 'да';
  if (['нет', 'false', 'no', 'отсутствует', 'выключено', 'off'].includes(low)) return 'нет';
  return null;
}

/** Факт источника в представление specs (boolean → да/нет). */
export function factToSpec(v) {
  if (typeof v === 'boolean') return v ? 'да' : 'нет';
  const b = canonBoolish(v);
  if (b) return b;
  return v;
}

const sameFact = (key, a, b, attr = null) => {
  if (typeof a === 'number' && typeof b === 'number') {
    return Math.abs(a - b) <= tolerance(key, b);
  }
  const ba = canonBoolish(a);
  const bb = canonBoolish(b);
  if (ba != null && bb != null) return ba === bb;
  if (enumValuesEqual(attr, a, b)) return true;
  return String(a).toLowerCase() === String(b).toLowerCase();
};

function attrForSpecKey(schema, key) {
  const attrs = schema?.dict?.attrs;
  if (!attrs) return null;
  for (const attr of attrs) {
    const dest = specDest(attr);
    const k = typeof dest === 'object' ? dest.key : dest;
    if (k === key) return attr;
  }
  return null;
}

/** Склеенный dump в факте — не с чем сверять модель. */
function scrubDumpFacts(facts) {
  if (!facts || typeof facts !== 'object') return facts;
  for (const [k, v] of Object.entries(facts)) {
    if (typeof v === 'string' && isGluedFactDump(v)) delete facts[k];
  }
  return facts;
}

/**
 * Чистит уже сохранённые карточки: dump в source_facts/specs и ложные warnings
 * (LED↔dump, R600a↔R600a,58). Без повторного обогащения.
 */
export function sanitizeEnrichedResult(data) {
  if (!data || typeof data !== 'object' || Array.isArray(data)) return data;
  const d = data;
  const facts = d.source_facts && typeof d.source_facts === 'object' ? d.source_facts : null;
  const specs = d.specs && typeof d.specs === 'object' ? d.specs : null;
  scrubDumpFacts(facts);

  const refrigerantCode = (v) => {
    const m = String(v ?? '').match(/\b(R-?\d{2,4}[A-Za-z]?)\b/i);
    return m ? m[1].replace(/-/g, '').replace(/^r/, 'R') : null;
  };

  if (Array.isArray(d.warnings)) {
    d.warnings = d.warnings.filter((w) => {
      if (!w || typeof w !== 'object') return false;
      if (typeof w.source === 'string' && isGluedFactDump(w.source)) {
        // dump затёр specs — вернём ответ модели (LED → Светодиодное).
        if (specs && w.field && isGluedFactDump(specs[w.field]) && w.model != null) {
          const m = String(w.model);
          specs[w.field] = /^led$/i.test(m.trim()) ? 'Светодиодное' : m;
        }
        return false;
      }
      if (w.field === 'тип_освещения'
        && /led/i.test(String(w.model || ''))
        && /светодиодн/i.test(String(w.source || ''))) return false;
      if (w.field === 'хладагент') {
        const a = refrigerantCode(w.model);
        const b = refrigerantCode(w.source);
        if (a && b && a.toLowerCase() === b.toLowerCase()) {
          if (specs && typeof specs.хладагент === 'string' && specs.хладагент !== a) {
            specs.хладагент = a;
          }
          if (facts && typeof facts.хладагент === 'string') facts.хладагент = a;
          return false;
        }
      }
      return true;
    });
  }

  if (specs) {
    for (const [k, v] of Object.entries(specs)) {
      if (typeof v === 'string' && isGluedFactDump(v)) specs[k] = null;
    }
    if (typeof specs.хладагент === 'string') {
      const code = refrigerantCode(specs.хладагент);
      if (code) specs.хладагент = code;
    }
  }
  if (facts && typeof facts.хладагент === 'string') {
    const code = refrigerantCode(facts.хладагент);
    if (code) facts.хладагент = code;
  }
  // Старые карточки: тип_управления как ["Механическое"]
  if (specs && Array.isArray(specs.тип_управления)) {
    const parts = specs.тип_управления.map(x => String(x ?? '').trim()).filter(Boolean);
    specs.тип_управления = parts[0] ?? null;
  }
  // Канон охлаждения — из словаря («No Frost» / «Full No Frost»).
  // Размораживание камер: голое No Frost → «Автоматическое (No Frost)».
  const plainDefrost = (v) => {
    const s = String(v ?? '').trim();
    if (!s) return null;
    if (/^no\s*frost$/i.test(s) || /^(total|full)\s*no\s*frost$/i.test(s)) {
      return displayEnum('автоматическое (No Frost)');
    }
    return null;
  };
  if (specs) {
    for (const k of ['размораживание_холодильной_камеры', 'размораживание_морозильной_камеры']) {
      const d = plainDefrost(specs[k]);
      if (d) specs[k] = d;
    }
    // Обрезок от «Тип конструкции»: «Конструкции -» / «конструкции - C …»
    if (typeof specs.тип_холодильника === 'string') {
      const t = specs.тип_холодильника.trim();
      if (/^конструкци/i.test(t) || /^тип\s+конструкци/i.test(t)) {
        if (/side\s*-?\s*by\s*-?\s*side/i.test(t) || /распашн/i.test(t)) {
          specs.тип_холодильника = 'Side-by-Side';
        } else {
          specs.тип_холодильника = null;
        }
      }
    }
  }
  if (facts) {
    for (const k of ['размораживание_холодильной_камеры', 'размораживание_морозильной_камеры']) {
      const d = plainDefrost(facts[k]);
      if (d) facts[k] = d;
    }
    if (typeof facts.тип_холодильника === 'string' && /^конструкци/i.test(facts.тип_холодильника.trim())) {
      const t = facts.тип_холодильника;
      facts.тип_холодильника = (/side\s*-?\s*by\s*-?\s*side/i.test(t) || /распашн/i.test(t))
        ? 'Side-by-Side'
        : null;
    }
  }
  // Климат: в specs одно «N», в facts полный «N, SN, ST, T» — берём полный, warning снимаем.
  if (specs && facts && typeof facts.климатический_класс === 'string') {
    const full = facts.климатический_класс.trim();
    const short = specs.климатический_класс != null ? String(specs.климатический_класс).trim() : '';
    if (full.includes(',') && short && full !== short
      && full.split(/\s*,\s*/).some(p => p.toUpperCase() === short.toUpperCase())) {
      specs.климатический_класс = full;
      if (Array.isArray(d.warnings)) {
        d.warnings = d.warnings.filter(w => w?.field !== 'климатический_класс');
      }
    }
  }
  if (Array.isArray(d.warnings)) {
    d.warnings = d.warnings.filter(w => {
      if (w?.field === 'тип_холодильника' && /^конструкци/i.test(String(w.model || ''))) return false;
      return true;
    });
  }
  return d;
}

// ── СВЕРКА ОТВЕТА С ФАКТАМИ ──────────────────────────────────
const NUM_TOLERANCE = { высота_мм: 20, ширина_мм: 20, глубина_мм: 20, вес_кг: 1 }; // округления в описаниях
const tolerance = (key, v) => NUM_TOLERANCE[key] ?? Math.max(1, Math.abs(v) * 0.02);
// Границу тоже берём с допуском: магазин относит холодильник 1800 мм к полке
// «От 181 до 190 см» просто округлив, и придираться к этому нечестно.
const withinBound = (key, v, b) => {
  const tol = tolerance(key, v);
  return v >= b.lo - tol && v <= b.hi + tol;
};

/**
 * Сравнивает specs модели с фактами источника. Точный факт всегда побеждает
 * модель (приоритет источника). `bounds` — интервалы без точного числа.
 *
 * Политики:
 *   prefer_source — перекрыть фактом, без warning (по умолчанию)
 *   flag          — перекрыть фактом и пометить расхождение
 *   strict        — как prefer_source для фактов; вне bounds / размеров — обнулить + warning
 */
export function crossCheck(specs, facts, bounds = {}, policy = MISMATCH_POLICY, schema = null) {
  const warnings = [];
  const flagged = new Set();
  const audit = policy === 'flag';
  const nullOutOfBound = policy === 'strict';
  scrubDumpFacts(facts);

  const noteWarn = (field, got, expected, note) => {
    if (flagged.has(field)) return;
    flagged.add(field);
    warnings.push({ field, model: got, source: expected, note });
  };

  for (const [key, exp] of Object.entries(facts)) {
    if (key === 'размеры_мм') continue;
    if (!(key in specs)) continue;
    const got = specs[key];
    if (got == null) continue;

    const attr = attrForSpecKey(schema, key);
    const mismatch = typeof exp === 'number'
      ? Math.abs(Number(got) - exp) > tolerance(key, exp)
      : !sameFact(key, got, exp, attr);
    if (!mismatch) continue;

    const corrected = attr && (attr.type === 'enum' || attr.type === 'text')
      ? (aliasValue(attr, exp) || (hasStrictEnum(attr) ? null : factToSpec(exp)))
      : factToSpec(exp);
    // Сырой факт без канона словаря не перетирает ответ модели.
    if (corrected == null) continue;
    specs[key] = corrected; // всегда приоритет источника
    if (audit) noteWarn(key, got, corrected, 'не совпало с текстом');
  }

  // Интервалы из атрибутов: поле, у которого есть точный факт, уже сверено выше.
  for (const [key, b] of Object.entries(bounds)) {
    if (key in facts) continue;
    const got = Number(specs[key]);
    if (specs[key] == null || !Number.isFinite(got) || withinBound(key, got, b)) continue;
    noteWarn(key, specs[key], null, `вне значения атрибута магазина («${b.source}»)`);
    if (nullOutOfBound) specs[key] = null;
  }

  // Оси без подписи: какая из трёх — не знаем, но само число обязано быть в тройке.
  if (Array.isArray(facts.размеры_мм)) {
    for (const key of ['ширина_мм', 'высота_мм', 'глубина_мм']) {
      if (key in facts) continue; // ось известна точно — уже сверена выше
      const got = specs[key];
      if (got == null) continue;
      const hit = facts.размеры_мм.some(x => Math.abs(x - Number(got)) <= 20);
      if (!hit) {
        noteWarn(key, got, null, `нет в размерах из текста (${facts.размеры_мм.join('×')} мм)`);
        if (nullOutOfBound) specs[key] = null;
      }
    }
  }

  return warnings;
}


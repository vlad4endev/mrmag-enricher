export function normalizeResponse(data, sourceText = '', schemaKey, attributes = [], policy = MISMATCH_POLICY, product = null) {
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    throw new Error('Ответ не объект');
  }
  // Явный undefined от вызывающего не должен обнулять политику по умолчанию.
  const mismatch = policy == null ? MISMATCH_POLICY : policy;
  const schema = schemaFor(schemaKey);
  const raw = data.specs && typeof data.specs === 'object' ? data.specs : {};
  const specs = {};
  const enumIssues = [];
  for (const k of schema.specKeys) {
    const v = raw[k];
    if (schema.numericKeys.includes(k)) {
      specs[k] = coerceNumber(Array.isArray(v) ? v[0] : v);
      continue;
    }
    const attr = attrForSpecKey(schema, k);
    // Модель иногда отдаёт enum как ["Механическое"] при ошибочном multi.
    let scalar = v;
    if (Array.isArray(v)) {
      const parts = v.map(x => String(x ?? '').trim()).filter(Boolean);
      if (attr?.cardinality === 'multi') {
        const joined = parts.join(', ');
        if (!joined || /^(нет данных|не указано|-|—|n\/?a)$/i.test(joined)) {
          specs[k] = null;
          continue;
        }
        const norm = normalizeValue(attr, joined, { keyText: attr.name });
        specs[k] = norm.ok ? norm.value : parts;
        continue;
      }
      scalar = parts[0] ?? null;
    }
    const s = scalar == null ? null : String(scalar).trim();
    const clean = s && !/^(нет данных|не указано|-|—|n\/?a)$/i.test(s) ? s : null;
    if (clean && isGluedFactDump(clean)) {
      specs[k] = null;
    } else if (clean && attr?.type === 'boolean') {
      // Overlay «Есть»/«Нет» — ярлык фильтра, не канон specs.
      const b = canonBoolish(clean);
      specs[k] = b;
      if (!b) {
        enumIssues.push({ field: k, model: clean, source: null, note: 'значение вне списка (да | нет)' });
      }
    } else if (clean && schema.enums[k]) {
      const viaAlias = attr ? aliasValue(attr, clean) : null;
      const snapped = viaAlias || snapEnum(clean, schema.enums[k]);
      if (!snapped) enumIssues.push({ field: k, model: clean, source: null, note: `значение вне списка (${schema.enums[k].join(' | ')})` });
      specs[k] = snapped ? (displayEnum(snapped) || snapped) : null;
    } else if (clean && attr && (attr.type === 'enum' || attr.type === 'text')) {
      const norm = normalizeValue(attr, clean, { keyText: attr.name });
      specs[k] = norm.ok ? norm.value : (aliasValue(attr, clean) || clean);
    } else {
      specs[k] = clean;
    }
  }

  // Полный product (с HTML annotation) — иначе stripHtml(sourceText) снова
  // склеивает пары и может подставить чужое число в source_facts.
  const factSrc = product && typeof product === 'object'
    ? product
    : { description: sourceText, attributes };
  const { facts, bounds, conflicts } = productFacts(factSrc, schema);
  scrubDumpFacts(facts);
  const warnings = crossCheck(specs, facts, bounds, mismatch, schema).concat(enumIssues);

  const filled_from_text = [];
  for (const k of schema.specKeys) {
    if (specs[k] != null || facts[k] == null) continue;
    const attr = attrForSpecKey(schema, k);
    if (attr && (attr.type === 'enum' || attr.type === 'text')) {
      const canon = aliasValue(attr, facts[k]);
      if (canon) {
        specs[k] = displayEnum(canon) || canon;
        filled_from_text.push(k);
      }
      // pending без канона — не копируем сленг источника в specs; это работа ИИ.
      continue;
    }
    specs[k] = factToSpec(facts[k]);
    filled_from_text.push(k);
  }

  const arr = v => (Array.isArray(v) ? v.map(x => String(x).trim()).filter(Boolean) : []);
  const str = v => {
    if (v == null) return null;
    if (typeof v !== 'string') return '';
    const s = v.trim();
    return s === '...' ? '' : s;
  };

  // Обратная совместимость: старые ответы с seo_description / seo_keywords.
  let description = str(data.description) ?? str(data.seo_description) ?? '';
  const meta_keywords = (() => {
    if (typeof data.meta_keywords === 'string') return str(data.meta_keywords) || '';
    if (Array.isArray(data.seo_keywords)) return data.seo_keywords.map(x => String(x).trim()).filter(Boolean).join(', ');
    return '';
  })();

  let short_description = str(data.short_description) || '';
  let bullets = arr(data.bullets);

  // Specs уже сверены с источником — цифры в прозе обязаны совпасть.
  const aligned = alignCardTextsToSpecs({ short_description, description, bullets }, specs);
  short_description = aligned.short_description;
  description = aligned.description;
  bullets = aligned.bullets;

  // Регистр strong подтягиваем к (уже выровненному) description; фразы вне текста отбрасываем.
  const strong = arr(data.strong)
    .map(s => matchLiteral(description, s))
    .filter(Boolean);

  let web_info = data.web_info;
  if (web_info === '') web_info = ''; // валидатор поймает
  else if (web_info == null) web_info = null;
  else web_info = str(web_info);

  return sanitizeEnrichedResult({
    specs,
    short_description,
    description,
    bullets,
    strong,
    meta_keywords,
    web_info,
    source_facts: facts,
    source_conflicts: conflicts,
    filled_from_text,
    prose_fixes: aligned.prose_fixes,
    warnings,
  });
}


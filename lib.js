/**
 * Извлекает из текста то, что берётся однозначно. Используется и как проверка
 * ответа модели, и как подсказка модели в промпте, и для добора пустых полей.
 */
export function extractFacts(text, schemaKey) {
  const t = String(text || '');
  if (!t) return {};
  const s = schemaFor(schemaKey);
  const f = commonFacts(t, s);

  for (const [key, label, unit] of s.labels) {
    const h = labeled(t, label);
    if (!h || !inRange(key, h.value, s.ranges)) continue;
    if (unit && !unit.test(h.tail) && !unit.test(h.gap) && !unit.test(h.head)) continue;
    f[key] = h.value;
  }

  s.extra(t, f, s.ranges);
  return f;
}

/**
 * Атрибуты товара → { facts, bounds, sources }. Первые два по полям схемы,
 * sources хранит исходную строку атрибута: без неё расхождение показывается
 * числом без объяснения, откуда оно взялось.
 */
export function attrFacts(attributes, schemaKey) {
  const s = schemaFor(schemaKey);
  const facts = {}, bounds = {}, sources = {};
  for (const a of Array.isArray(attributes) ? attributes : []) {
    const name = String(a?.name ?? '');
    const spec = s.attrs.find(([, re]) => re.test(name));
    if (!spec) continue;
    const [key, , parse] = spec;
    const got = parse(String(a?.value ?? ''));
    if (got == null) continue;
    sources[key] = `${name}: ${a.value}`;
    if (typeof got === 'object') bounds[key] = { ...got, source: sources[key] };
    else if (typeof got === 'string' || inRange(key, got, s.ranges)) facts[key] = got;
  }
  return { facts, bounds, sources };
}

/**
 * Факты товара из обоих источников сразу. Расходятся — не утверждаем ничего:
 * тот же принцип, что и с «No Frost» рядом с «капельной» внутри одного текста.
 * Спор магазина с самим собой не разрешается догадкой в нашу пользу.
 */
export function productFacts(product, schemaKey) {
  const facts = extractFacts(sourceText(product), schemaKey);
  const { facts: attr, bounds, sources } = attrFacts(product?.attributes, schemaKey);
  // Спор не проглатывается молча: это ошибка в самом каталоге, и её владелец —
  // магазин, а не модель. Собираем отдельно от warnings, которые про модель.
  const conflicts = [];
  const drop = (field, text) => {
    conflicts.push({ field, text, attr: sources[field] });
    delete facts[field];
    delete bounds[field];
  };

  for (const [k, v] of Object.entries(attr)) {
    if (!(k in facts)) { facts[k] = v; continue; }
    if (!sameFact(k, facts[k], v)) drop(k, facts[k]);
  }
  // Число из текста вне интервала атрибута — тот же спор источников.
  for (const [k, b] of Object.entries(bounds)) {
    if (facts[k] == null) continue;
    if (withinBound(k, Number(facts[k]), b)) delete bounds[k];  // интервал уже подтверждён точным числом
    else drop(k, facts[k]);
  }
  return { facts, bounds, conflicts };
}

const sameFact = (key, a, b) => (typeof a === 'number' && typeof b === 'number'
  ? Math.abs(a - b) <= tolerance(key, b)
  : String(a).toLowerCase() === String(b).toLowerCase());

// ── СВЕРКА ОТВЕТА С ФАКТАМИ ──────────────────────────────────
const NUM_TOLERANCE = { высота_мм: 20, ширина_мм: 20, глубина_мм: 20, вес_кг: 1 }; // округления в описаниях
const tolerance = (key, v) => NUM_TOLERANCE[key] ?? Math.max(1, Math.abs(v) * 0.02);
// Границу тоже берём с допуском: магазин относит холодильник 1800 мм к полке
// «От 181 до 190 см» просто округлив, и придираться к этому нечестно.
const withinBound = (key, v, b) => {
  const tol = tolerance(key, v);
  return v >= b.lo - tol && v <= b.hi + tol;
};

/**
 * Сравнивает specs модели с фактами источника. `bounds` — интервалы из
 * атрибутов магазина: точного значения там нет, но выход за границы — такое же
 * расхождение. Возвращает список расхождений; при MISMATCH_POLICY='strict'
 * спорное поле модели обнуляется.
 */
export function crossCheck(specs, facts, bounds = {}, policy = MISMATCH_POLICY) {
  const warnings = [];
  const flagged = new Set();
  const flag = (field, got, expected, note) => {
    if (flagged.has(field)) return; // одно расхождение на поле, а не два по разным путям
    flagged.add(field);
    warnings.push({ field, model: got, source: expected, note });
    if (policy === 'strict') specs[field] = expected ?? null;
  };

  for (const [key, exp] of Object.entries(facts)) {
    if (key === 'размеры_мм') continue;
    if (!(key in specs)) continue;
    const got = specs[key];
    if (got == null) continue;

    if (typeof exp === 'number') {
      if (Math.abs(Number(got) - exp) > tolerance(key, exp)) flag(key, got, exp, 'не совпало с текстом');
    } else if (String(got).toLowerCase() !== String(exp).toLowerCase()) {
      flag(key, got, exp, 'не совпало с текстом');
    }
  }

  // Интервалы из атрибутов: поле, у которого есть точный факт, уже сверено выше.
  for (const [key, b] of Object.entries(bounds)) {
    if (key in facts) continue;
    const got = Number(specs[key]);
    if (specs[key] == null || !Number.isFinite(got) || withinBound(key, got, b)) continue;
    flag(key, specs[key], null, `вне значения атрибута магазина («${b.source}»)`);
  }

  // Оси без подписи: какая из трёх — не знаем, но само число обязано быть в тройке.
  if (Array.isArray(facts.размеры_мм)) {
    for (const key of ['ширина_мм', 'высота_мм', 'глубина_мм']) {
      if (key in facts) continue; // ось известна точно — уже сверена выше
      const got = specs[key];
      if (got == null) continue;
      const hit = facts.размеры_мм.some(x => Math.abs(x - Number(got)) <= 20);
      if (!hit) flag(key, got, null, `нет в размерах из текста (${facts.размеры_мм.join('×')} мм)`);
    }
  }

  return warnings;
}

// ── РАЗБОР ОТВЕТА ────────────────────────────────────────────
export function parseResponse(text) {
  if (!text?.trim()) throw new Error('Пустой ответ');
  const clean = text
    .replace(/^```json\s*/i, '')
    .replace(/^```\s*/i, '')
    .replace(/\s*```$/i, '')
    .trim();
  try {
    const p = JSON.parse(clean);
    return Array.isArray(p) ? p[0] : p;
  } catch {
    const m = clean.match(/\{[\s\S]*\}/);
    if (m) {
      const p = JSON.parse(m[0]);
      return Array.isArray(p) ? p[0] : p;
    }
    throw new Error(`Не удалось распарсить JSON: ${clean.slice(0, 80)}`);
  }
}

/**
 * Обрыв по max_tokens почти всегда режет хвост: specs уже написаны, а
 * seo_description оборван на полуслове. Закрываем строку и скобки — иначе
 * весь товар уходит в ошибку из-за одного незакрытого абзаца.
 */
export function repairTruncatedJson(text) {
  if (!text) return null;
  let s = String(text)
    .replace(/^```json\s*/i, '')
    .replace(/^```\s*/i, '')
    .replace(/\s*```$/i, '')
    .trim();
  try {
    const p = JSON.parse(s);
    return Array.isArray(p) ? p[0] : p;
  } catch { /* чиним */ }

  let inString = false, escape = false;
  const stack = [];
  for (const ch of s) {
    if (inString) {
      if (escape) { escape = false; continue; }
      if (ch === '\\') { escape = true; continue; }
      if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') { inString = true; continue; }
    if (ch === '{') stack.push('}');
    else if (ch === '[') stack.push(']');
    else if ((ch === '}' || ch === ']') && stack[stack.length - 1] === ch) stack.pop();
  }
  if (inString) s += '"';
  s = s.replace(/,\s*$/, '');
  s += stack.reverse().join('');
  try {
    const p = JSON.parse(s);
    return Array.isArray(p) ? p[0] : p;
  } catch {
    return null;
  }
}

// Модель отвечает «Есть», «ЕСТЬ», «имеется» на поле со списком ["да","нет"] —
// три разных фасета вместо одного. Приводим то, что однозначно, остальное
// считаем значением вне списка.
const ENUM_ALIAS = {
  'есть': 'да', 'имеется': 'да', 'true': 'да', 'присутствует': 'да', 'yes': 'да',
  'отсутствует': 'нет', 'false': 'нет', 'no': 'нет', 'без': 'нет',
};

// Кириллические двойники латиницы: модель пишет «4К» русской К, и строгое
// сравнение теряет верное значение фасета. Сводим то и другое к одному виду.
const LOOKALIKE = { 'а': 'a', 'в': 'b', 'е': 'e', 'к': 'k', 'м': 'm', 'н': 'h', 'о': 'o', 'р': 'p', 'с': 'c', 'т': 't', 'у': 'y', 'х': 'x' };
const deLookalike = s => s.replace(/[авекмнорстух]/g, c => LOOKALIKE[c]);

/** Значение из закрытого списка либо null. Регистр и алиасы не в счёт. */
function snapEnum(value, allowed) {
  const raw = String(value).trim();
  const low = raw.toLowerCase();
  const flat = deLookalike(low);
  const hit = allowed.find(a => a.toLowerCase() === low)
    || allowed.find(a => a.toLowerCase() === ENUM_ALIAS[low])
    || allowed.find(a => deLookalike(a.toLowerCase()) === flat);
  return hit ?? null;
}

// Длины SEO-полей. Выход за границы не ошибка модели, а причина посмотреть
// глазами: title длиннее 60 символов поисковик обрежет, короче 30 — потеряет
// ключи. Поэтому это заметка в seo_issues, а не обнуление поля. Отдельно от
// warnings: там расхождения с текстом источника, то есть повод не доверять
// значению, а здесь — повод причесать текст.
const SEO_LIMITS = {
  seo_title:         [30, 60],
  h1:                [10, 70],
  meta_description:  [120, 170],
  short_description: [40, 200],
  seo_description:   [900, 2200],
};
const SEO_TEXT_KEYS = Object.keys(SEO_LIMITS);

// Длинному тексту нужен материал: на товаре с двумя характеристиками 900
// символов честно не написать. Требовать их — значит требовать домыслов,
// поэтому порог основного текста зависит от того, сколько полей заполнено.
const RICH_SPECS = 5;
const seoFloor = (key, filled) =>
  (key === 'seo_description' && filled < RICH_SPECS ? 400 : SEO_LIMITS[key][0]);

export function normalizeResponse(data, sourceText = '', schemaKey, attributes = [], policy = MISMATCH_POLICY) {
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    throw new Error('Ответ не объект');
  }
  const schema = schemaFor(schemaKey);
  const raw = data.specs && typeof data.specs === 'object' ? data.specs : {};
  const specs = {};
  const enumIssues = [];
  for (const k of schema.specKeys) {
    const v = raw[k];
    if (schema.numericKeys.includes(k)) {
      specs[k] = coerceNumber(v);
      continue;
    }
    const s = v == null ? null : String(v).trim();
    const clean = s && !/^(нет данных|не указано|-|—|n\/?a)$/i.test(s) ? s : null;
    // Поле со списком значений — фасет фильтра. Чужое значение туда пускать
    // нельзя: один «фронтальный тип» ломает всю группу фильтра.
    if (clean && schema.enums[k]) {
      const snapped = snapEnum(clean, schema.enums[k]);
      if (!snapped) enumIssues.push({ field: k, model: clean, source: null, note: `значение вне списка (${schema.enums[k].join(' | ')})` });
      specs[k] = snapped;
    } else {
      specs[k] = clean;
    }
  }

  // Источника два: проза и атрибуты магазина. productFacts сводит их вместе и
  // молчит там, где они спорят друг с другом.
  const { facts, bounds, conflicts } = productFacts({ description: sourceText, attributes }, schema);
  const warnings = crossCheck(specs, facts, bounds, policy).concat(enumIssues);

  // Пропуск модели — не повод терять факт: если поле null, а в тексте значение
  // разобрано однозначно, подставляем его и перечисляем, что подставили.
  const filled_from_text = [];
  for (const k of schema.specKeys) {
    if (specs[k] != null || facts[k] == null) continue;
    specs[k] = facts[k];
    filled_from_text.push(k);
  }

  const arr = v => (Array.isArray(v) ? v.map(x => String(x).trim()).filter(Boolean) : []);
  const str = v => (typeof v === 'string' ? v.trim() : '');

  const seo = {};
  const seo_issues = [];
  const filledSpecs = Object.values(specs).filter(v => v != null).length;
  for (const k of SEO_TEXT_KEYS) {
    seo[k] = str(data[k]);
    const min = seoFloor(k, filledSpecs), max = SEO_LIMITS[k][1];
    const len = seo[k].length;
    if (!len) { seo_issues.push(`${k}: пусто`); continue; }
    if (len < min || len > max) seo_issues.push(`${k}: ${len} симв., рекомендуется ${min}–${max}`);
  }

  return {
    specs,
    ...seo,
    bullets:         arr(data.bullets),
    synonyms:        arr(data.synonyms),
    search_aliases:  arr(data.search_aliases),
    seo_keywords:    arr(data.seo_keywords),
    source_facts:    facts,
    source_conflicts: conflicts,
    filled_from_text,
    warnings,
    seo_issues,
  };
}

// ── ТЕЛО ЗАПРОСА ─────────────────────────────────────────────
export function buildUserContent(product, facts = null) {
  return JSON.stringify({
    facts:       facts && Object.keys(facts).length ? facts : undefined,
    name:        product.name,
    sku:         product.sku,
    brand:       product.brand || undefined,   // бренд по классификации магазина
    category:    product.category,
    description: stripHtml(product.description),
    annotation:  stripHtml(product.annotation),
    attributes:  product.attributes || [],
    price:       product.price,
  });
}

export function sourceText(product) {
  return (stripHtml(product.description) + ' ' + stripHtml(product.annotation)).trim();
}

/**
 * Артикул из названия: «Холодильник LG GC-Q247CAMT» → «GC-Q247CAMT».
 *
 * По нему проверяется, что найденная в сети страница описывает именно этот
 * товар, а не соседнюю модель того же бренда. Скобки выбрасываем: там обычно
 * внутренний код магазина («HBD 1182.3 M NF H (78091)»), которого на чужом
 * сайте нет и быть не может. Артикул — слово с буквами и не меньше чем двумя
 * цифрами: «2-камерный» цифрой не отличается от «2862-90», а двумя — да.
 */
export function modelToken(name) {
  const words = String(name || '')
    .replace(/\([^)]*\)/g, ' ')
    .replace(/["«»,;]/g, ' ')
    .split(/\s+/);
  let best = null;
  for (const w of words) {
    const token = w.replace(/[.:]+$/, '');
    if (!/^[\p{L}\d][\p{L}\d./_-]*$/u.test(token)) continue;
    const norm = token.replace(/[^\p{L}\d]/gu, '');
    if (norm.length < 4) continue;
    if ((norm.match(/\d/g) || []).length < 2) continue;
    if (!best || norm.length > best.norm.length) best = { token, norm };
  }
  return best ? best.token : null;
}

/**
 * Пустую карточку ещё можно добрать из сети, если в названии есть
 * артикул или другие опознавательные слова (бренд, модель).
 * «Холодильник белый» — нет: по такому имени чужую карточку не отличить.
 */
export function canSearchWeb(product) {
  if (modelToken(product?.name)) return true;
  return nameKeyTokens(product?.name, product?.brand).length > 0;
}

/**
 * Стоит ли платить за запрос по этому товару.
 * Короткий текст сам по себе не приговор — важно, есть ли в нём что извлекать.
 * Возвращает { ok } либо { ok:false, reason } для пометки в выгрузке.
 *
 * Отказ с web:true — это «своего текста нет, но товар опознаваем по имени»:
 * такой товар до модели ещё может дойти, если описание найдётся в сети
 * (ensureSource в catalog.js). Сеть здесь не трогается: фильтр в интерфейсе
 * обязан считаться мгновенно и на любом количестве товаров.
 */
export function isEnrichable(product, schemaKey) {
  const web = canSearchWeb(product);
  const text = sourceText(product);
  if (!text) return { ok: false, reason: 'нет ни description, ни annotation', web };
  const factCount = Object.keys(extractFacts(text, schemaKey)).length;
  if (text.length < MIN_SOURCE_CHARS && factCount === 0) {
    return { ok: false, reason: `текст ${text.length} симв. и ни одной распознанной характеристики`, web };
  }
  return { ok: true };
}

/** Верх ретрая при обрыве. Совпадает с потолком max_tokens в настройках. */
export const MAX_COMPLETION_TOKENS = 16_000;

/**
 * DeepSeek/Qwen по умолчанию думают вслух. Цепочка рассуждений и JSON делят
 * один max_tokens: thinking съедает бюджет, finish_reason=length, карточка
 * пустая. Для извлечения характеристик рассуждения не нужны — выключаем.
 * Чужим моделям эти поля не шлём: часть шлюзов падает на неизвестном ключе.
 */
function thinkingOff(model) {
  const m = String(model || '').toLowerCase();
  if (!/deepseek|qwen|qwq/.test(m)) return {};
  return {
    thinking: { type: 'disabled' },
    reasoning: { enabled: false, effort: 'none' },
    enable_thinking: false,
  };
}

function buildRequestBody(model, product, maxTokens = 3200, schemaKey) {
  return {
    model,
    max_tokens:  maxTokens,
    temperature: 0.1,
    // Снимает причину ошибок парсинга вместо того, чтобы лечить их ретраями.
    response_format: { type: 'json_object' },
    // Возвращает фактическую стоимость запроса — не считаем её сами.
    usage: { include: true },
    ...thinkingOff(model),
    messages: [
      { role: 'system', content: buildSystemPrompt(schemaKey) },
      { role: 'user',   content: product },
    ],
  };
}

// ── RATE LIMITER ─────────────────────────────────────────────
// Проверено прогоном: обе ветки рабочие, окно срабатывает как основная.
export const sleep = ms => new Promise(r => setTimeout(r, ms));

export class RateLimiter {
  constructor(rpm, extraDelayMs = 0) {
    this.rpm      = rpm;
    this.minDelay = Math.ceil(60_000 / rpm) + extraDelayMs;
    this.lastCall = 0;
    this.window   = [];
  }
  async wait(onWait) {
    // Очередь обязательна: без неё параллельные вызовы читают одно и то же
    // состояние окна, все проходят проверку и rpm перестаёт соблюдаться.
    const prev = this.tail || Promise.resolve();
    let release;
    this.tail = new Promise(r => { release = r; });
    await prev;
    try { await this.#slot(onWait); } finally { release(); }
  }

  async #slot(onWait) {
    const now = Date.now();
    this.window = this.window.filter(t => now - t < 60_000);
    if (this.window.length >= this.rpm) {
      const waitMs = 60_000 - (now - this.window[0]) + 150;
      onWait?.(waitMs);
      await sleep(waitMs);
    } else {
      const since = Date.now() - this.lastCall;
      if (since < this.minDelay) await sleep(this.minDelay - since);
    }
    this.lastCall = Date.now();
    this.window.push(this.lastCall);
  }
}

// Rate limits OpenRouter (rpm). Неизвестная модель — консервативные 20.
const MODEL_RPM = {
  'deepseek/deepseek-v3.2':          20,
  'deepseek/deepseek-v3.2-20251201': 20,
  'deepseek/deepseek-chat':          20,
  'openai/gpt-4o':                  500,
  'openai/gpt-4o-mini':             500,
  'anthropic/claude-haiku-4-5':      50,
  'anthropic/claude-3-haiku':        50,
  'google/gemini-2.5-flash-preview': 30,
  'google/gemini-flash-1.5':         60,
};
export const rpmFor = model => MODEL_RPM[model] || 20;


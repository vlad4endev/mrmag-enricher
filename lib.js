const RETRYABLE = new Set([408, 409, 429, 500, 502, 503, 504, 524]);

/** Сколько ждать по заголовкам ответа. Провайдер знает это точнее нас. */
function retryAfterMs(res) {
  const ra = res.headers.get('retry-after');
  if (ra) {
    const sec = Number(ra);
    if (Number.isFinite(sec)) return Math.min(60_000, Math.max(0, sec * 1000));
    const at = Date.parse(ra);
    if (Number.isFinite(at)) return Math.min(60_000, Math.max(0, at - Date.now()));
  }
  const reset = Number(res.headers.get('x-ratelimit-reset'));
  if (Number.isFinite(reset) && reset > 0) {
    // Заголовок приходит и в миллисекундах epoch, и в секундах epoch.
    const ms = (reset > 1e12 ? reset : reset * 1000) - Date.now();
    if (ms > 0) return Math.min(60_000, ms);
  }
  return null;
}

function overlayDump(product, dump) {
  if (!product || !dump) return product;
  const next = { ...product };
  if (String(dump.annotation || '').trim()) next.annotation = dump.annotation;
  if (String(dump.description || '').trim()) next.description = dump.description;
  return next;
}

function slimCard(enriched) {
  if (!enriched || typeof enriched !== 'object') return null;
  return {
    specs: enriched.specs,
    short_description: enriched.short_description,
    description: enriched.description,
    bullets: enriched.bullets,
    strong: enriched.strong,
    meta_keywords: enriched.meta_keywords,
    web_info: enriched.web_info,
    warnings: enriched.warnings || [],
  };
}

function productDumpKey(product) {
  const v = product?.sku ?? product?.id ?? product?.article;
  return v == null ? null : String(v).trim() || null;
}

function schemaCatId(schema, product, root) {
  if (schema?.id != null) return String(schema.id);
  if (schema?.dict?.catId != null) return String(schema.dict.catId);
  if (product?.category_id != null) return String(product.category_id);
  return resolveCatId(product?.category, root);
}

/**
 * Один товар → обогащённая запись.
 * До двух попыток на валидацию: 1) исходный промпт, 2) перечень ошибок.
 * Если остались расхождения с источником или карточка «на проверку» —
 * ещё один проход: сверка с дампом и текстом, сразу, до следующего товара.
 * После неудачи правки — needs_review (не done, не в выгрузку v2).
 * Токены и стоимость суммируются. Сеть/HTTP ретраятся в пределах тех же попыток.
 */
export async function enrichProduct(product, opts) {
  const {
    model, apiKey, limiter, pricing = null, schema: schemaOpt = null,
    maxRetries = 2, maxTokens = 3200, timeoutMs = 60_000,
    onNote = () => {}, referer = 'https://mrmag.ru', title = 'Ogran',
    chatUrl = 'https://openrouter.ai/api/v1/chat/completions',
    headers: extraHeaders = {},
    mismatchPolicy = MISMATCH_POLICY,
    systemPrompt = '',
  } = opts;

  let schema;
  try {
    schema = schemaForProduct(product, schemaOpt, opts.root);
  } catch (e) {
    if (e?.code === 'DICT_UNAVAILABLE') {
      const reason = e.message;
      const marker = `MODEL_NOT_CALLED: ${reason}`;
      return {
        enriched: null,
        needs_review: true,
        validation_issues: [{
          field: 'schema',
          reason,
          kind: 'dict_unavailable',
          action: 'needs_review',
        }],
        raw_response: marker,
        iT: 0,
        oT: 0,
        cost: null,
        costSource: 'нет данных',
        attempts: 0,
        debug: {
          source_text: sourceText(product) || marker,
          system_prompt: marker,
          user_content: marker,
          raw_response: marker,
          enriched_result: null,
          model_status: 'MODEL_NOT_CALLED',
          model_called: false,
          error: reason,
          validation_issues: [{ field: 'schema', reason }],
          resolved_category: e.resolved_category,
          dict_debug: e.dict_debug || null,
          dict_debug_text: e.dict_debug_text || null,
        },
      };
    }
    throw e;
  }
  const src = sourceText(product);
  const { facts } = productFacts(product, schema);
  const benchmarks = schema.id != null ? loadBenchmarks(schema.id, opts.root) : null;
  const baseUser = buildUserContent(product, facts, { benchmarks });
  const attemptsCap = Math.min(2, Math.max(1, maxRetries));
  let tokenBudget = maxTokens;
  let lastErr;
  let lastIssues = [];
  let feedback = '';
  // Фактический payload последнего model call — не реконструкция из финального товара.
  let sentSystem = null;
  let sentUser = null;
  let lastRaw = '';
  let lastEnriched = null;
  let modelCalled = false;
  let modelStatus = 'MODEL_NOT_CALLED';

  let iT = 0, oT = 0, cost = 0, costSource = 'нет данных';
  const usage = () => ({ iT, oT, cost: costSource === 'нет данных' ? null : cost });
  const safeErr = (e) => {
    const msg = String(e?.message || e || 'unknown error').slice(0, 500);
    return msg.replace(/Bearer\s+\S+/gi, 'Bearer ***').replace(/sk-[a-zA-Z0-9_-]+/g, 'sk-***');
  };
  const debugOf = (extra = {}) => ({
    source_text: src,
    system_prompt: sentSystem ?? (modelCalled ? null : `MODEL_NOT_CALLED: запрос к модели не отправлялся`),
    user_content: sentUser ?? (modelCalled ? null : `MODEL_NOT_CALLED: запрос к модели не отправлялся`),
    raw_response: lastRaw,
    enriched_result: lastEnriched,
    model_status: modelStatus,
    model_called: modelCalled,
    validation_issues: lastIssues,
    ...extra,
  });
  const fail = (e, status = 'MODEL_ERROR') => {
    modelStatus = status;
    const err = e instanceof Error ? e : new Error(String(e));
    if (!lastRaw) lastRaw = `${status}: ${safeErr(err)}`;
    else if (status === 'MODEL_ERROR' && !String(lastRaw).startsWith('MODEL_ERROR')) {
      // сырой ответ провайдера уже есть — статус/причина отдельно в error
    }
    err.usage = usage();
    err.debug = debugOf({ error: safeErr(err) });
    throw err;
  };
  const pack = (result) => ({
    ...result,
    debug: debugOf({ attempts: result.attempts, error: result.error || null }),
  });

  const userPayload = () => {
    if (!feedback) return baseUser;
    try {
      const obj = JSON.parse(baseUser);
      obj.validation_feedback = feedback;
      return JSON.stringify(obj);
    } catch {
      return baseUser + '\n\n' + feedback;
    }
  };

  const logValidationFail = (issues, attempt, raw) => {
    lastIssues = issues;
    lastRaw = raw;
    const list = issues.map(i => `${i.field}: ${i.reason}`).join('; ');
    onNote(`валидация не прошла · попытка ${attempt}/${attemptsCap}: ${list}`, { level: 'warn', step: 'validate' });
    onNote(`сырой ответ модели (попытка ${attempt}):\n${raw}`, { level: 'warn', step: 'validate' });
  };

  for (let attempt = 1; attempt <= attemptsCap; attempt++) {
    await limiter.wait(ms => onNote(`rate limit ${ms}ms`));

    const userContent = userPayload();
    onNote(`запрос к модели${attempt > 1 ? ` · попытка ${attempt}/${attemptsCap}` : ''}…`);

    // Собираем тело заранее и логируем ИМЕННО его messages — то, что уйдёт в fetch.
    const requestBody = buildRequestBody(model, userContent, tokenBudget, schema, systemPrompt);
    sentSystem = requestBody.messages?.[0]?.content ?? null;
    sentUser = requestBody.messages?.[1]?.content ?? null;
    modelCalled = true;
    modelStatus = 'ok';

    let res, data, bodyText;
    try {
      res = await fetch(chatUrl, {
        method:  'POST',
        headers: {
          Authorization:    `Bearer ${apiKey}`,
          'Content-Type':   'application/json',
          'HTTP-Referer':   referer,
          'X-Title':        title,
          ...extraHeaders,
        },
        body:   JSON.stringify(requestBody),
        signal: AbortSignal.timeout(timeoutMs),
      });
      bodyText = await res.text();
      lastRaw = bodyText;
    } catch (e) {
      let host = chatUrl;
      try { host = new URL(chatUrl).host; } catch { /* */ }
      const timed = e.name === 'TimeoutError' || e.cause?.name === 'TimeoutError';
      lastErr = new Error(timed ? `таймаут ${timeoutMs}ms (${host})` : `${host}: ${netError(e)}`);
      lastRaw = `MODEL_ERROR: ${safeErr(lastErr)}`;
      modelStatus = 'MODEL_ERROR';
      if (attempt < attemptsCap) { onNote(`сеть, retry ${attempt}`); await sleep(attempt * 3000); continue; }
      fail(lastErr);
    }

    try { data = JSON.parse(bodyText); } catch { data = null; }

    if (!res.ok || data?.error) {
      const code = data?.error?.code ?? res.status;
      const msg  = data?.error?.message || `HTTP ${res.status}: ${bodyText.slice(0, 120)}`;
      lastErr = new Error(msg);
      lastRaw = `MODEL_ERROR: ${safeErr(lastErr)}`;
      modelStatus = 'MODEL_ERROR';
      if (attempt < attemptsCap && RETRYABLE.has(Number(code))) {
        const wait = retryAfterMs(res) ?? attempt * 4000;
        onNote(`${code}, retry ${attempt}, ${wait}ms`);
        await sleep(wait);
        continue;
      }
      fail(lastErr);
    }

    const choice = data?.choices?.[0];
    if (!choice) {
      lastErr = new Error('Нет choices в ответе');
      lastRaw = 'MODEL_EMPTY_RESPONSE';
      modelStatus = 'MODEL_EMPTY_RESPONSE';
      if (attempt < attemptsCap) { onNote(`пустой ответ, retry ${attempt}`); await sleep(attempt * 5000); continue; }
      fail(lastErr, 'MODEL_EMPTY_RESPONSE');
    }

    const inTok  = data.usage?.prompt_tokens     ?? 0;
    const outTok = data.usage?.completion_tokens ?? 0;
    iT += inTok;
    oT += outTok;
    if (typeof data.usage?.cost === 'number') {
      cost += data.usage.cost;
      costSource = /openrouter\.ai/i.test(chatUrl) ? 'openrouter' : 'провайдер';
    } else if (pricing && (pricing.prompt || pricing.completion)) {
      cost += inTok * pricing.prompt + outTok * pricing.completion;
      if (costSource === 'нет данных') costSource = 'тариф модели';
    }

    const content = choice.message?.content ?? '';
    if (!String(content).trim()) {
      lastRaw = 'MODEL_EMPTY_RESPONSE';
      modelStatus = 'MODEL_EMPTY_RESPONSE';
      lastErr = new Error('MODEL_EMPTY_RESPONSE');
      if (attempt < attemptsCap) { onNote(`пустой content, retry ${attempt}`); await sleep(attempt * 5000); continue; }
      fail(lastErr, 'MODEL_EMPTY_RESPONSE');
    }
    lastRaw = content; // сырой ответ ДО parse/normalize

    let parsedBody = null;
    if (choice.finish_reason === 'length') {
      try { parsedBody = parseResponse(content); } catch { /* */ }
      if (!parsedBody) parsedBody = repairTruncatedJson(content);
      if (!parsedBody) {
        if (attempt < attemptsCap && tokenBudget < MAX_COMPLETION_TOKENS) {
          tokenBudget = Math.min(MAX_COMPLETION_TOKENS, tokenBudget * 2);
          onNote(`обрыв по длине, max_tokens→${tokenBudget}`);
          continue;
        }
        fail(new Error(`Ответ обрезан на max_tokens=${tokenBudget}`));
      }
    } else {
      try {
        parsedBody = parseResponse(content);
      } catch (err) {
        lastErr = err;
        if (attempt < attemptsCap) { onNote(`parse err, retry ${attempt}`); await sleep(2000); continue; }
        fail(err);
      }
    }

    let enriched;
    try {
      enriched = normalizeResponse(parsedBody, src, schema, product.attributes, mismatchPolicy, product);
      lastEnriched = enriched;
    } catch (err) {
      lastErr = err;
      if (attempt < attemptsCap) { onNote(`normalize err, retry ${attempt}`); await sleep(2000); continue; }
      fail(err);
    }

    const filledSpecs = Object.values(enriched.specs || {}).filter(v => v != null).length;
    // DeepSeek часто даёт 6 bullets / 97 симв. short — чиним без второго запроса.
    softFixCardTexts(enriched);
    const issues = validateModelResponse({
      specs: enriched.specs,
      short_description: enriched.short_description,
      description: enriched.description,
      bullets: enriched.bullets,
      strong: enriched.strong,
      meta_keywords: enriched.meta_keywords,
      web_info: enriched.web_info,
    }, {
      filledSpecs,
      requireSpecFill: Boolean(src && src.length >= MIN_SOURCE_CHARS),
    });

    if (issues.length) {
      // Обрыв по длине + пустые тексты: сначала поднять бюджет, а не жечь попытку feedback.
      if (choice.finish_reason === 'length'
        && attempt < attemptsCap
        && tokenBudget < MAX_COMPLETION_TOKENS
        && cardTextsEmpty(enriched)) {
        tokenBudget = Math.min(MAX_COMPLETION_TOKENS, tokenBudget * 2);
        onNote(`обрыв по длине, max_tokens→${tokenBudget}`);
        continue;
      }
      logValidationFail(issues, attempt, content);
      if (attempt < attemptsCap) {
        feedback = validationFeedbackLine(issues, { filledSpecs });
        onNote(`повтор с указанием ошибок валидации`);
        continue;
      }
      // Карточка есть — в выгрузку не пойдёт (needs_review), но UI/лог её видят.
      modelStatus = 'needs_review';
      return pack({
        enriched,
        needs_review: true,
        validation_issues: issues,
        raw_response: content,
        ...usage(),
        costSource,
        attempts: attempt,
      });
    }

    modelStatus = 'ok';
    return pack({ enriched, ...usage(), costSource, attempts: attempt });
  }

  fail(lastErr || new Error('Не удалось обогатить'));
}

/** Детали для раздела «Логи», когда модель не вызывалась (gate/skip/нет ключа). */

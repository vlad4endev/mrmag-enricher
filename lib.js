/**
 * Схема для товара, категория которого неизвестна или не описана. Раньше её
 * роль играл холодильник — и телевизор получал в промпте «объём морозильной
 * камеры». Универсальные поля дают меньше, но не выдумывают лишнего.
 */
export const GENERIC_SCHEMA = defineSchema({
  slug: '_generic', name: 'Товары', subject: 'товаров каталога', tallest: false,
  fields: [
    ...IDENT, ['назначение', 'str'],
    ['мощность_вт', 'num'], ['напряжение_в', 'num'], ['объем_л', 'num'],
    ['комплектация', 'str'], ...DIMS, ...TAIL,
  ],
  labelKeys: [...BASE_LABELS, 'мощность_вт', 'напряжение_в', 'объем_л'],
  hints: ['Категория неизвестна: тип_товара определи по названию, лишних полей не выдумывай'],
});

/** Схема по slug, id категории, названию или объекту схемы. */
export function schemaFor(key) {
  if (!key) return GENERIC_SCHEMA;
  if (typeof key === 'object') return key.specKeys ? key : GENERIC_SCHEMA;
  const k = String(key).trim();
  if (SCHEMAS[k]) return SCHEMAS[k];
  const lower = k.toLowerCase();
  return Object.values(SCHEMAS).find(s => String(s.id) === k)
    || Object.values(SCHEMAS).find(s => s.name.toLowerCase() === lower)
    // Категория товара из фида — это путь вида «Техника для дома/Холодильники».
    // Самый точный раздел стоит в пути последним, поэтому выигрывает совпадение
    // правее: иначе холодильник получил бы схему «Техники для дома».
    || Object.values(SCHEMAS)
         .map(s => ({ s, at: Math.max(lower.lastIndexOf(s.name.toLowerCase()), lower.lastIndexOf(s.slug)) }))
         .filter(x => x.at >= 0)
         .sort((a, b) => b.at - a.at || b.s.name.length - a.s.name.length)[0]?.s
    || GENERIC_SCHEMA;
}


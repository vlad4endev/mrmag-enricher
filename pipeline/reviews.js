/**
 * web_info — выдержка из отзывов покупателей.
 *
 * В эталоне заказчика поле сырое: кратные пробелы, вырезанное название модели
 * («Отзыв о      Н--П3Д»), а у части товаров вместо отзыва текст «о компании»
 * с сайта производителя. Формат копируем, артефакты — нет.
 *
 * Отзыва нет — поле пустое, товар уходит в отчёт. Выдумывать отзывы нельзя.
 */

export const WEB_INFO = { min: 300, max: 700 };

/** Текст «о компании», а не отзыв покупателя. */
const CORPORATE_RE = new RegExp([
  'десятилетиями\\s+мы', 'наша\\s+компания', 'наше\\s+предприятие',
  'мы\\s+прилагаем', 'наши\\s+усилия', 'наша\\s+миссия', 'мы\\s+производим',
  'мировой\\s+лидер', 'лидер\\s+рынка', 'о\\s+компании', 'наш\\s+бренд',
  'компания\\s+(?:основана|была\\s+основана)', 'официальный\\s+(?:дилер|представитель)',
  'модельный\\s+ряд\\s+бренда', 'история\\s+бренда',
].join('|'), 'i');

/** Оценочные конструкции от первого лица — признак настоящего отзыва. */
const FIRST_PERSON_RE = new RegExp([
  'куп(?:ил|ила|или)', 'взял(?:а|и)?', 'польз(?:уюсь|уемся|овались|овался|овалась)',
  'довол(?:ен|ьна|ьны)', 'рекоменду(?:ю|ем)', 'не\\s+жале(?:ю|ем)',
  'мне\\s+нравится', 'нам\\s+нравится', 'за\\s+эти\\s+деньги',
  'работает\\s+уже', 'сто[ий]т\\s+своих\\s+денег', 'посоветовал[иа]?',
  'впечатлени[ея]', 'сове(?:тую|туем)',
].join('|'), 'i');

/** Разметка отзыва на маркетплейсах. */
const PROS_RE = /досто[иі]нства|плюсы/i;
const REVIEW_MARK_RE = /досто[иі]нства|недостатки|плюсы|минусы|комментарий/i;

/**
 * Схлопывает кратные пробелы, снимает служебный префикс «Отзыв о …» и
 * обрывки названий модели вида «Н--П3Д», оставшиеся от вырезания имени.
 */
export function cleanReviewText(raw) {
  let t = String(raw ?? '')
    .replace(/\u00a0/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!t) return '';
  // «Отзыв о <что-то>.» / «Отзыв на …:» — служебный префикс источника.
  // \b не видит кириллицу: «о» для JS не слово, граница не срабатывает.
  t = t.replace(/^отзыв\s+(?:о|об|на)[\s:][^.:!?]{0,80}[.:!?]?\s*/i, '');
  // Обрывок названия: токен с двумя и более дефисами подряд.
  t = t.replace(/(?:^|\s)[A-Za-zА-Яа-яЁё0-9]*-{2,}[A-Za-zА-Яа-яЁё0-9]*(?=\s|$)/g, ' ');
  return t.replace(/\s+([,.!?;:])/g, '$1').replace(/\s+/g, ' ').trim();
}

/** Отзыв ли это: есть разметка отзыва либо оценка от первого лица. */
export function isReview(text) {
  const t = String(text || '');
  if (!t) return false;
  if (CORPORATE_RE.test(t)) return false;
  return REVIEW_MARK_RE.test(t) || FIRST_PERSON_RE.test(t);
}

/**
 * Обрезает по границе предложения. Середину предложения не режем: лучше
 * пустое поле, чем оборванная фраза.
 */
export function trimToSentence(text, min = WEB_INFO.min, max = WEB_INFO.max) {
  const t = String(text || '').trim();
  if (t.length <= max) return t;
  const window = t.slice(0, max + 1);
  let cut = -1;
  for (const m of window.matchAll(/[.!?](?=\s|$)/g)) cut = m.index + 1;
  return cut >= min ? window.slice(0, cut).trim() : '';
}

/** Связный фрагмент с достоинствами, если источник размечен «Достоинства/Недостатки». */
function pickFragment(text) {
  const at = text.search(PROS_RE);
  return at > 0 ? text.slice(at) : text;
}

/**
 * Из сырого источника — готовое значение web_info либо '' (в отчёт).
 * @param {string} raw текст отзыва со страницы источника
 * @returns {string} 300–700 знаков либо пустая строка
 */
export function webInfoFrom(raw) {
  const cleaned = cleanReviewText(raw);
  if (!cleaned || !isReview(cleaned)) return '';
  const frag = pickFragment(cleaned);
  const out = trimToSentence(frag);
  if (out.length < WEB_INFO.min || out.length > WEB_INFO.max) return '';
  return isReview(out) ? out : '';
}
